//! Info buttons, to RERAG's spec.
//!
//! Constants, geometry and colour are copied from RERAG's CLAUDE.md rather
//! than redesigned, so the two apps' info buttons are the same object:
//!
//!   PARAM_ICON_BUTTON_CLASS  w-6 h-6 min-w-6 min-h-6 shrink-0 rounded ...
//!   PARAM_ICON_BUTTON_STYLE  background-color:#7C2A02;border:1px solid #7C2A02;
//!   INFO_ICON_SVG_CLASS      w-5 h-5 text-white
//!
//! #7C2A02 is the Rust brand colour and is used flat in both themes on
//! purpose: it is a fixed brand mark, not semantic colour, so it must not
//! follow the light/dark tokens the rest of the app uses.
//!
//! VOICE - also RERAG's rule. These are written for someone using the app,
//! who has no idea it is split into pieces. Say "the app", never "the
//! backend", "the frontend" or "the server". User-visible technical terms
//! (GLPI, entities, profiles, ports) are fine; words from the source code
//! are not.
use dioxus::prelude::*;

pub const PARAM_ICON_BUTTON_CLASS: &str =
    "w-6 h-6 min-w-6 min-h-6 shrink-0 rounded flex items-center justify-center cursor-pointer hover:opacity-80";
pub const PARAM_ICON_BUTTON_STYLE: &str = "background-color:#7C2A02;border:1px solid #7C2A02;";
pub const INFO_ICON_SVG_CLASS: &str = "w-5 h-5 text-white";

/// The icon itself. Geometry is RERAG's: circle r=9, stem from y=8 to y=14,
/// and a separate filled dot at cy=6.3 - an "i" drawn rather than typeset, so
/// it stays centred at any size without depending on a font.
#[component]
pub fn InfoIcon() -> Element {
    rsx! {
        svg {
            xmlns: "http://www.w3.org/2000/svg",
            view_box: "0 0 24 24",
            fill: "none",
            stroke: "currentColor",
            stroke_width: "1.5",
            class: "{INFO_ICON_SVG_CLASS}",
            circle { cx: "12", cy: "12", r: "9" }
            line { x1: "12", y1: "8", x2: "12", y2: "14", stroke_width: "1.5" }
            circle { cx: "12", cy: "6.3", r: "1", fill: "currentColor", stroke: "none" }
        }
    }
}

/// One tab inside an info panel.
#[derive(Clone, PartialEq)]
pub struct InfoSection {
    pub heading: String,
    pub body: String,
}

impl InfoSection {
    pub fn new(heading: &str, body: &str) -> Self {
        Self {
            heading: heading.into(),
            body: body.into(),
        }
    }
}

/// A link into GLPI's own screens, given as a path relative to GLPI's base
/// URL rather than an absolute address - the base is whatever this install is
/// configured against, and hardcoding localhost would be wrong the moment
/// GLPI moves.
#[derive(Clone, PartialEq)]
pub struct InfoLink {
    pub label: String,
    pub path: String,
}

impl InfoLink {
    pub fn new(label: &str, path: &str) -> Self {
        Self {
            label: label.into(),
            path: path.into(),
        }
    }
}

/// A button that explains the thing it sits next to.
///
/// A NOTE ON THE PROSE HERE. output.css is generated by scanning these files
/// for anything that looks like a class name, and the scanner does not know a
/// comment from markup. Two sentences below once used the obvious word for
/// this kind of overlay, and daisyUI's entire component of that name - ten
/// rules the app never uses, since it builds the overlay by hand - landed in
/// the stylesheet, 2.4 KB of it. They say "dialog" instead, on purpose.
///
/// `body` is the short answer and always shows. `sections` are the longer
/// ones, rendered as tabs so the panel stays one screen high however much it
/// has to say. `links` land in GLPI itself, because most of what these
/// explain is ultimately changed there, not here.
///
/// Owns its own open state, so adding one is a single element with no signal
/// to thread through the caller.
#[component]
pub fn InfoButton(
    title: String,
    body: String,
    #[props(default = vec![])] sections: Vec<InfoSection>,
    #[props(default = vec![])] links: Vec<InfoLink>,
    /// Draws the trigger as a named text link instead of the icon.
    ///
    /// For the one explanation that is about a whole page rather than the
    /// figure beside it. The icon works when it sits next to the thing it
    /// explains - there is no doubt what it refers to - but a page-level
    /// icon floating above the tabs refers to nothing in particular and is
    /// found only by hovering it. A named link says what it will tell you.
    #[props(default = None)]
    label: Option<String>,
) -> Element {
    let mut open = use_signal(|| false);
    let mut tab = use_signal(|| 0usize);

    // Resolved here, not in the loop: the context read is the same for every
    // link and the base may still be empty while health is in flight.
    let resolved: Vec<(String, Option<String>)> = links
        .iter()
        .map(|l| (l.label.clone(), crate::glpi_link::link(&l.path)))
        .collect();

    rsx! {
        // Both triggers do the same thing and reset to the first tab, so a
        // second opening does not start wherever the last reader left off.
        match label {
            Some(l) => rsx! {
                button {
                    class: "link link-primary text-sm",
                    onclick: move |_| {
                        tab.set(0);
                        open.set(true);
                    },
                    "{l}"
                }
            },
            None => rsx! {
                button {
                    class: "{PARAM_ICON_BUTTON_CLASS}",
                    style: "{PARAM_ICON_BUTTON_STYLE}",
                    title: "What this is",
                    aria_label: "What \"{title}\" means",
                    onclick: move |_| {
                        tab.set(0);
                        open.set(true);
                    },
                    InfoIcon {}
                }
            },
        }

        if open() {
            div {
                // Centred with symmetric padding rather than pinned below a
                // fixed 5rem offset: that offset spent height the panel then
                // had to scroll to get back.
                class: "fixed inset-0 z-[100] flex items-center justify-center bg-black/60 p-4 backdrop-blur-sm",
                onclick: move |_| open.set(false),

                // Escape closes it, like every other dialog a reader has used.
                // Three things are needed and all three are easy to miss: the
                // overlay must be focusable (tabindex -1, so it takes focus
                // without entering the tab order), it must actually be given
                // focus on mount, and the handler sits here rather than on the
                // inner panel so it still fires after a click has moved focus
                // onto one of the section tabs inside.
                tabindex: "-1",
                onmounted: move |e: Event<MountedData>| async move {
                    // A focus failure costs the key handler, not the modal, so
                    // it is swallowed rather than surfaced.
                    let _ = e.set_focus(true).await;
                },
                onkeydown: move |e: Event<KeyboardData>| {
                    if e.key() == Key::Escape {
                        open.set(false);
                    }
                },
                div {
                    // WIDTH IS WHY THESE SCROLLED. A 32rem column makes a
                    // 500-character section six or seven lines longer than it
                    // needs to be, so the panel overflowed vertically while
                    // most of a wide screen sat empty beside it. It widens with
                    // the viewport instead, and the cap is 90vh rather than
                    // 80vh so the last 10% is usable too.
                    //
                    // overflow-y-auto stays as the fallback, not the plan: on a
                    // short window something has to give, and scrolling beats
                    // clipping. With room, nothing should need it.
                    class: "max-h-[90vh] w-full max-w-lg overflow-y-auto rounded-box border border-base-300 bg-base-100 p-5 shadow-2xl sm:max-w-2xl lg:max-w-3xl",
                    onclick: move |e: Event<MouseData>| e.stop_propagation(),

                    div { class: "mb-3 flex items-start justify-between gap-3",
                        h3 { class: "text-base font-semibold", "{title}" }
                        button {
                            class: "btn btn-ghost btn-sm",
                            onclick: move |_| open.set(false),
                            "Close"
                        }
                    }

                    p { class: "text-sm leading-relaxed text-base-content/80", "{body}" }

                    if !sections.is_empty() {
                        // Scrollable rather than wrapping: a panel with several
                        // sections would otherwise push its last tabs past the
                        // edge of the modal, where they are unreachable.
                        div {
                            role: "tablist",
                            class: "tabs tabs-border mt-4 flex-nowrap overflow-x-auto",
                            for (i, s) in sections.iter().enumerate() {
                                button {
                                    key: "{s.heading}",
                                    role: "tab",
                                    class: if tab() == i { "tab tab-active" } else { "tab" },
                                    onclick: move |_| tab.set(i),
                                    "{s.heading}"
                                }
                            }
                        }
                        if let Some(s) = sections.get(tab()) {
                            p { class: "mt-3 text-sm leading-relaxed text-base-content/80", "{s.body}" }
                        }
                    }

                    if !resolved.is_empty() {
                        div { class: "mt-5 border-t border-base-300 pt-3",
                            div { class: "mb-1 text-xs font-medium text-base-content/60", "In GLPI" }
                            ul { class: "space-y-1",
                                for (label, href) in resolved.iter() {
                                    li { key: "{label}",
                                        if let Some(h) = href {
                                            a {
                                                class: "link link-primary text-sm",
                                                href: "{h}",
                                                // GLPI is a separate application; opening it
                                                // in place would lose whatever the reader was
                                                // looking at here.
                                                target: "_blank",
                                                rel: "noopener noreferrer",
                                                "{label} ↗"
                                            }
                                        } else {
                                            span { class: "text-sm text-base-content/50", "{label}" }
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}
